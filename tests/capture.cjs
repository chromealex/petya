const assert = require('node:assert/strict');
const { installCapture, configureCapture } = require('../src/capture.cjs');
(async () => {
  for (const [platform, electronVersion, expected] of [['darwin', '43.8.6', true], ['darwin', '44.0.0', true], ['darwin', '45.0.0', false], ['darwin', '38.0.0', false], ['win32', '43.8.6', false]]) {
    let value = 'ExistingFeature';
    const app = { commandLine: { getSwitchValue: () => value, appendSwitch: (key, next) => { assert.equal(key, 'disable-features'); value = next; } } };
    configureCapture({ app, platform, electronVersion });
    configureCapture({ app, platform, electronVersion });
    assert.equal(value, expected ? 'ExistingFeature,MacCatapLoopbackAudioForScreenShare' : 'ExistingFeature');
  }
  let permission, display, options;
  const win = { webContents: { getURL: () => 'file:///petya', mainFrame: {} } };
  const session = { setPermissionCheckHandler() {}, setPermissionRequestHandler(fn) { permission = fn; }, setDisplayMediaRequestHandler(fn, opts) { display = fn; options = opts; } };
  installCapture({ session, win, entry: 'file:///petya', platform: 'darwin', desktopCapturer: { getSources: async () => [{ id: 'screen:0' }] } });
  assert.equal(options.useSystemPicker, false);
  const allowed = (who, kind, types) => { let value; permission(who, kind, r => value = r, { mediaTypes: types }); return value; };
  assert.equal(allowed(win.webContents, 'display-capture', ['video', 'audio']), true);
  assert.equal(allowed(win.webContents, 'media', ['video']), false);
  assert.equal(allowed(win.webContents, 'media', ['audio']), true);
  assert.equal(allowed({}, 'display-capture', ['video']), false);
  let grant;
  await display({ frame: win.webContents.mainFrame, videoRequested: true, audioRequested: false }, r => grant = r);
  assert.deepEqual(grant, { video: { id: 'screen:0' } });
  await display({ frame: win.webContents.mainFrame, videoRequested: true, audioRequested: true }, r => grant = r);
  assert.equal(grant.audio, 'loopback');
  await display({ frame: {}, videoRequested: true, audioRequested: true }, r => grant = r);
  assert.deepEqual(grant, {});
  installCapture({ session, win, entry: 'file:///petya', platform: 'win32', desktopCapturer: { getSources: async () => [{ id: 'screen:0' }] } });
  assert.equal(options.useSystemPicker, false);
  await display({ frame: win.webContents.mainFrame, videoRequested: true, audioRequested: true }, r => grant = r);
  assert.equal(grant.audio, 'loopback');
  const vm = require('node:vm');
  const context = vm.createContext({ setTimeout, clearTimeout });
  vm.runInContext(require('node:fs').readFileSync(require.resolve('../src/ui/audio.js'), 'utf8'), context);
  assert.match(context.meetingCaptureError({ message: 'Invalid capture constraints' }).message, /ошибка захвата/);
  assert.match(context.meetingCaptureError({ name: 'NotAllowedError' }).message, /отменён/);
  const other = new Error('unrelated');
  assert.equal(context.meetingCaptureError(other), other);
  let stopped = 0;
  const video = { stop: () => stopped++ };
  context.window = { petyaPlatform: 'darwin' };
  context.navigator = { mediaDevices: { getDisplayMedia: async () => ({ getAudioTracks: () => [], getTracks: () => [video] }) } };
  await assert.rejects(context.captureMeetingAudio(), /аудиодорожка не получена/);
  assert.equal(stopped, 1);
  const ended = { readyState: 'ended', stop: () => stopped++ };
  context.navigator.mediaDevices.getDisplayMedia = async () => ({ getAudioTracks: () => [ended], getTracks: () => [video, ended] });
  await assert.rejects(context.captureMeetingAudio(), /полностью завершите/);
  assert.equal(stopped, 3);
  const live = { readyState: 'live', stop: () => stopped++ };
  const stream = { getAudioTracks: () => [live], getTracks: () => [video, live] };
  context.navigator.mediaDevices.getDisplayMedia = async () => stream;
  assert.equal(await context.captureMeetingAudio(), stream);
  assert.equal(stopped, 3);
  // A timed-out OS request must not start capture later or allow overlapping requests.
  let timeout, resolveCapture;
  context.setTimeout = callback => { timeout = callback; return 1; };
  context.clearTimeout = () => {};
  context.navigator.mediaDevices.getDisplayMedia = () => new Promise(resolve => { resolveCapture = resolve; });
  const waiting = context.captureMeetingAudio();
  await assert.rejects(context.captureMeetingAudio(), /Предыдущий запрос/);
  timeout();
  await assert.rejects(waiting, /20 секунд/);
  await assert.rejects(context.captureMeetingAudio(), /Предыдущий запрос/);
  resolveCapture(stream);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(stopped, 5);
  context.navigator.mediaDevices.getDisplayMedia = async () => stream;
  assert.equal(await context.captureMeetingAudio(), stream);
  console.log('Capture permissions: display allowed, camera and foreign frames denied, requested tracks only');
})().catch(e => { console.error(e); process.exitCode = 1; });
