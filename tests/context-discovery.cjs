const assert=require('node:assert/strict');
const feature=require('../src/features/context-discovery.cjs');
const {isContextReference}=require('../src/context-reference.cjs');
const now=Date.now(),project={id:'general',name:'Общее'};
const zoom=(id,sessionId,at,text)=>({id,sessionId,at,text,source:'Zoom',title:'Встреча'});
const slack=(id,channel,text,user='alex')=>({id,channel,text,user,at:now,source:'Slack',title:text,url:'https://app.slack.com/archives/'+channel+'/p123',messages:[{user,text,at:now}]});
(async()=>{
 for(const text of ['посмотри что не так','Петя, глянь, что там не так?','разберись в чём проблема','можешь проверить что случилось','проверь почему не работает'])assert(isContextReference(text),text);
 for(const text of ['не посмотри что не так','посмотри что не так и удали проект','проверь почту'])assert(!isContextReference(text),text);
 const rows=[zoom('old','old',now-3*3600000,'Старая встреча'),zoom('a','new',now-200,'Не работает вход'),zoom('b','new',now-100,'После обновления'),slack('s','C1','Проверь авторизацию')];
 const resolve=(extra={})=>feature.resolve({rows,project,now,...extra});
 assert.deepEqual(resolve().rows.map(r=>r.id),['a','b']);
 // A recording that restarted a few minutes earlier is the same meeting.
 assert.deepEqual(feature.resolve({rows:[...rows,zoom('c','restart',now-5*60000,'Начало встречи')],project,now}).rows.map(r=>r.id),['c','a','b']);
 assert.equal(resolve({rows:[rows[3]]}).kind,'found');
 assert.equal(resolve({rows:[rows[3]],members:['other']}).kind,'empty');
 assert.equal(resolve({rows:[rows[3]],topic:{excludedMaterials:['s']}}).kind,'empty');
 assert.equal(resolve({rows:[rows[3],slack('s2','C2','Помоги с ошибкой')]}).kind,'clarify');
 assert.deepEqual(resolve({rows:[rows[3],slack('s2','C2','Помоги с ошибкой')],project:{id:'p',name:'Bunker'},channels:[{id:'C1'}]}).rows.map(r=>r.id),['s']);
 assert.deepEqual(resolve({project:{id:'p',name:'Bunker'}}).rows.map(r=>r.id),['a','b']);
 assert.equal(resolve({rows:[zoom('stale','old',now-8*86400000,'Ошибка')]}).kind,'empty');
 assert.equal(resolve({rows:[zoom('future','x',now+1000,'Ошибка')]}).kind,'empty');
 let saved=0,seen;
 const state={projects:[project],activeProjectId:'general',topics:[]};
 const s={dialogue:{state,active:()=>state.topics.find(t=>t.id===state.activeId),persist:()=>saved++},attachments:{list:()=>[]},requestProgress:{report(){}},projectMemory:{context:()=>({})},memory:{prune:()=>rows},modules:{enabled:()=>true},settings:{},team:{members:()=>[]},analyzeMaterials:async(t,q)=>{seen={t,q};return 'Сбой входа после обновления. Проверь ответ сервера.';}};
 const service=feature.setup(s).contextDiscovery;
 const result=await service.turn('посмотри что не так');
 assert.match(result.text,/Сбой входа/);assert.equal(seen.q,'посмотри что не так');assert.equal(seen.t.attachments.length,2);assert(saved>=2);
 assert.deepEqual(seen.t.messages[1].usedMaterials.map(r=>r.id),['a','b']);
 for(const follow of ['а почему?','посмотри это','нет, другое','проверь что не так','проверь почту'])assert.equal(await service.turn(follow),null);
 state.topics=[];state.activeId='';let refreshed=false;
 s.memory.prune=()=>refreshed?[slack('fresh','C1','Проверь ошибку входа')]:[];
 s.slackSync={start:async()=>{refreshed=true;}};
 assert.match((await service.turn('посмотри что не так')).text,/Slack/);
 assert(refreshed);assert.equal(s.dialogue.active().attachments[0].contextId,'fresh');
 state.topics=[];state.activeId='';refreshed=false;
 s.slackSync.start=async()=>{throw Error('offline');};
 assert.match((await service.turn('посмотри что не так')).text,/offline/);
 s.modules.enabled=()=>false;
 s.memory.prune=()=>[slack('disabled','C1','Проверь ошибку входа')];
 assert.equal((await service.turn('посмотри что не так')).question,true);
 console.log('Context discovery: phrasing, Zoom sessions, Slack requests, project isolation, exclusions, retention and persisted follow-ups passed');
})().catch(e=>{console.error(e);process.exitCode=1;});
